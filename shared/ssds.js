export function ssdsItemCount(languageMode) {
  return languageMode === "nonverbal" ? 58 : 71;
}

export function scoreSsds(answers, languageMode = "verbal") {
  const itemCount = ssdsItemCount(languageMode);
  const itemScores = {};
  for (let number = 1; number <= itemCount; number += 1) {
    const value = Number(answers?.[number]);
    if (!Number.isInteger(value) || value < 1 || value > 5) return null;
    itemScores[number] = SSDS_REVERSE_ITEMS.has(number) ? 6 - value : value;
  }

  const factorScores = Object.fromEntries(SSDS_FACTORS.map((factor) => {
    const score = factor.items.reduce((sum, number) => sum + itemScores[number], 0);
    return [factor.key, {
      label: factor.label,
      score,
      max: factor.items.length * 5,
      average: Math.round((score / factor.items.length) * 100) / 100,
      items: factor.items,
    }];
  }));
  const total = Object.values(itemScores).reduce((sum, value) => sum + value, 0);
  return {
    itemCount,
    total,
    max: itemCount * 5,
    average: Math.round((total / itemCount) * 100) / 100,
    factors: factorScores,
  };
}
